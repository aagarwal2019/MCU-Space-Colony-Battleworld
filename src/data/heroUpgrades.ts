/**
 * Initializes a hero with default Tier 1 and upgrade data if defined.
 */
export function enrichHeroWithUpgradeData(hero: MCUHero): MCUHero {
  const def = HERO_UPGRADE_DEFINITIONS[hero.id];
  if (!def) {
    return {
      ...hero,
      tier: hero.tier || 1,
      upgradeCost: hero.upgradeCost || { scrap: 300, vibraniumCredits: 50, chronoCores: 2 },
    };
  }

  return {
    ...hero,
    tier: hero.tier || 1,
    upgradeCost: def.upgradeCost,
    upgradedForm: {
      heroName: def.upgradedName,
      title: def.title,
      lore: def.lore,
      quote: def.quote,
      passiveBonus: def.passiveBonus,
      abilityName: def.abilityName,
      abilityDesc: def.abilityDesc,
      abilityCooldownSec: def.abilityCooldownSec,
      statBoost: def.statBoost,
    },
  };
}

/**
 * Ascends a hero from Tier 1 to Tier 2 Multiverse Apex form
 */
export function evolveHeroToTier2(hero: MCUHero): MCUHero {
  const def = HERO_UPGRADE_DEFINITIONS[hero.id];
  if (!def) {
    return {
      ...hero,
      tier: 2,
      heroName: `${hero.heroName} (Multiverse Apex)`,
      title: `Apex Multiverse ${hero.title}`,
      stats: {
        engineering: Math.min(100, hero.stats.engineering + 20),
        science: Math.min(100, hero.stats.science + 20),
        combat: Math.min(100, hero.stats.combat + 20),
        leadership: Math.min(100, hero.stats.leadership + 20),
      },
      ability: {
        ...hero.ability,
        name: `Apex ${hero.ability.name}`,
        description: `Multiverse empowered: ${hero.ability.description}`,
        cooldownSec: Math.max(30, hero.ability.cooldownSec - 15),
      },
    };
  }

  return {
    ...hero,
    tier: 2,
    heroName: def.upgradedName,
    title: def.title,
    lore: def.lore,
    quote: def.quote,
    passiveBonus: def.passiveBonus,
    stats: {
      engineering: Math.min(100, hero.stats.engineering + def.statBoost),
      science: Math.min(100, hero.stats.science + def.statBoost),
      combat: Math.min(100, hero.stats.combat + def.statBoost),
      leadership: Math.min(100, hero.stats.leadership + def.statBoost),
    },
    ability: {
      ...hero.ability,
      name: def.abilityName,
      description: def.abilityDesc,
      cooldownSec: def.abilityCooldownSec,
    },
  };
}
